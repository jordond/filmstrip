  @Test
  fun `reports what the encoders can do`() =
    runTest(timeout = TIMEOUT) {
      val result = withContext(Dispatchers.Default) { filmstrip.capabilities() }
      val capabilities = assertIs<CapabilitiesResult.Success>(result).capabilities

      assertTrue(capabilities.video.isNotEmpty(), "expected at least one video encoder")
      if (isSimulator()) {
        // The simulator has no hardware video encode path at all, so VideoToolbox reports every
        // encoder as software there. That is an environment limit, not a finding about the
        // mechanism, so it is reported rather than dressed up as a failure. Run macosArm64Test for
        // the real claim.
        println("skipping the hardware assertion on the simulator, which has no hardware encoder")
      } else {
        assertTrue(capabilities.video.all { it.isHardwareAccelerated == true }, "VideoToolbox encoders are hardware")
      }
      capabilities.audio
        .single()
        .codec.name shouldBe "Aac"

      // This machine's own answer varies with its silicon, so this only checks the probe is wired
      // to something real: a claimed HDR encoder has to be one this device actually lists.
      if (capabilities.supportsHdrEncoding) {
        assertTrue(
          capabilities.video.any { it.codec == VideoCodec.Hevc },
          "HDR support was claimed for a codec this device does not list",
        )
      }
    }

