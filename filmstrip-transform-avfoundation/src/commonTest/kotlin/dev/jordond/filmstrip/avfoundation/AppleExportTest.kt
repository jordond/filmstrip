        TimeRange.of(Duration.ZERO, 1_500.milliseconds),
        TimeRange.of(1_500.milliseconds, 3_000.milliseconds),
        TimeRange.of(3_000.milliseconds, 4_500.milliseconds),
        TimeRange.of(4_500.milliseconds, 5_300.milliseconds),
