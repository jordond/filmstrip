  /**
   * Exports [edit] and reads its one track's seams off the file.
   *
   * Every sample sits on a slot and the file holds one for each slot the track covers. At each seam the slot before
   * shows the clip before and the slot it opens on shows the clip after, told apart by which of the two clips' middles
   * the frame reads closer to.
   */
  private suspend fun assertLaidOnTheGrid(
    edit: EditComposition,
    spec: ExportSpec,
  ) {
    val rate = spec.frameRate.shouldNotBeNull()
    val laid = lowered(edit, spec).tracks.single().clips
    val file = probe.export(probe.plan(edit, spec))

    val times = videoSampleTimes(file)
    assertOneSampleOnEverySlot(times, outputSlotOf(laid.last().span.endExclusive!!, rate), rate)

    laid.zipWithNext().forEach { (before, after) ->
      val opens = outputSlotsOf(after.span, rate).first
      val middleBefore = eightBitFrameAt(file, before.span.start + before.duration / 2).grid()
      val middleAfter = eightBitFrameAt(file, after.span.start + after.duration / 2).grid()
      val last = eightBitFrameAt(file, outputSlotTime(opens - 1, rate)).grid()
      val first = eightBitFrameAt(file, outputSlotTime(opens, rate)).grid()
      withClue("slot ${opens - 1} does not show the clip before the seam") {
        (spread(last, middleBefore) < spread(last, middleAfter)) shouldBe true
      }
      withClue("slot $opens does not show the clip after the seam") {
        (spread(first, middleAfter) < spread(first, middleBefore)) shouldBe true
      }
    }
  }

