  /**
   * The tone each fixture carries, measured rather than assumed.
   *
   * What every assertion here compares is a gain, so the level the two sines happen to be written
   * at has to divide out along with the codec's. Read past the head of the file, where an AAC
   * decoder emits its priming samples.
   */
  private fun sourceTones(
    primary: File,
    bed: File,
  ): SourceTones =
    SourceTones(
      primary = decodeAudio(primary).amplitudeOver(EARLY_AT, WINDOW, PRIMARY_HZ),
      bed = decodeAudio(bed).amplitudeOver(EARLY_AT, WINDOW, BED_HZ),
    )

  /**
   * How loud each source's own tone is before anything is done to it.
   */
  private class SourceTones(
    val primary: Float,
    val bed: Float,
  )

  /**
   * The gain the bed plays at over the [window] centred on [at], on the scale the plan folds to.
   *
   * Both tones ride the same encode, so dividing one by the other cancels whatever the codec did to
   * the absolute level and leaves the ratio the two gains stand in. [primaryGain] is what the plan
   * folded for the track being divided by, so a primary that is itself scaled cannot read as a
   * louder bed.
   *
   * A window over a linear ramp reads its mean, which for a window centred on the point being asked
   * about is the value at that point.
   */
  private fun DecodedAudio.bedGainAt(
    at: Duration,
    window: Duration,
    tones: SourceTones,
    primaryGain: Float,
  ): Float {
    val from = at - window / 2
    val bed = amplitudeOver(from, window, BED_HZ)
    val primary = amplitudeOver(from, window, PRIMARY_HZ)
    // Guards the division rather than bounding an error. The primary plays across every window
    // measured here, so one that reads nothing is a decode that stopped, not a bed that behaved.
    withClue("the primary reads $primary at $at, so nothing was decoded there") {
      (primary > tones.primary * AUDIBLE) shouldBe true
    }
    return bed / primary * primaryGain * (tones.primary / tones.bed)
  }

  /**
   * Which laid pass covers [at].
   */
  private fun List<ResolvedClip>.passCovering(at: Duration): Int {
    val index = indexOfLast { it.span.start <= at }
    withClue("$at sits before the first of $size laid passes") { (index >= 0) shouldBe true }
    val clip = this[index]
    withClue("$at falls in the gap after pass ${index + 1}, which ends at ${clip.span.start + clip.duration}") {
      (at < clip.span.start + clip.duration) shouldBe true
    }
    return index
  }

  /**
   * Pins every laid pass of this track by which clip of the track it plays and by the span it holds,
   * against the run [passesCovering] derives for [lengths] over a composition of [duration].
   *
   * Whether the track loops decides how much of that composition it covers, so a track laid down
   * once is held to its own clips rather than to the whole run.
   */
  private fun ResolvedTrack.pinSchedule(
    lengths: List<Duration>,
    duration: Duration,
  ) {
    val expected =
      passesCovering(lengths, runLengthOf(looping, start, lengths, duration)).map { pass ->
        Triple(pass.index, start + pass.offset, start + pass.offset + pass.length)
      }

    withClue("the laid clips are not the run passesCovering derives") {
      clips.map { Triple(it.sourceIndex, it.span.start, it.span.endExclusive) } shouldBe expected
    }
  }

  /**
   * Reads the bed's level at [reading] and holds it to the gain [laid] folded for that pass.
   */
  private fun DecodedAudio.readBed(
    laid: List<ResolvedClip>,
    reading: LoopingCases.Reading,
    tones: SourceTones,
    under: ResolvedClip,
  ): Float {
    val clip = laid[reading.pass]
    val at = clip.span.start + reading.into
    val expected = clip.gain.gainAt(reading.into)
    val measured = bedGainAt(at, LOOP_WINDOW, tones, under.gain.gainAt(at))
    withClue(
      "the bed read $measured at $at, ${reading.into} into pass ${reading.pass + 1} of ${laid.size}, " +
        "where the plan folded $expected",
    ) {
      (abs(measured - expected) <= MEASURED_GAIN_TOLERANCE) shouldBe true
    }
    return measured
  }

  /**
   * A grid of patch averages over the frame, so a claim about the picture is not made from one pixel
   * that chroma subsampling could have moved anywhere.
   */
  private fun Bitmap.grid(): List<Triple<Int, Int, Int>> =
    FRAME_ACROSS.flatMap { x -> FRAME_DOWN.map { y -> averageAt(x, y) } }

  /**
   * The row of patches across the one band of the test pattern that moves between frames.
   */
  private fun Bitmap.band(): List<Triple<Int, Int, Int>> = FRAME_ACROSS.map { averageAt(it, MOVING_BAND) }

  /**
   * How far apart two rows of patches read, summed over the row.
   */
  private fun spread(
    a: List<Triple<Int, Int, Int>>,
    b: List<Triple<Int, Int, Int>>,
  ): Int = a.zip(b).sumOf { (one, other) -> distance(one, other) }

  /**
   * Holds the written duration to [plan]'s, within one output frame short and one output frame plus
   * one AAC access unit long, and holds whatever was written past one frame to silence.
   *
   * The two allowances differ because a muxer tail only ever adds. Nothing may hide inside the long
   * one, so the stretch past a frame is read for both tones against the levels [tones] says the
   * sources were recorded at. Both the access unit and the frame come off what was written rather
   * than off a figure repeated here: the unit from [decoded]'s own rate, the frame from [plan] or
   * from what [written] reports.
   */
  private fun assertRunsFor(
    written: MediaInfo,
    decoded: DecodedAudio,
    tones: SourceTones,
    plan: ExportPlan,
  ) {
    val rate = plan.output.frameRate
    val frame = (MILLIS_PER_SECOND / rate).milliseconds
    val accessUnit = AAC_UNIT_SAMPLES.seconds / decoded.sampleRate
    withClue(
      "the file runs ${written.duration} and decodes ${decoded.duration} of audio, where the plan is " +
        "${plan.duration} and the allowance is one $frame frame plus one $accessUnit access unit",
    ) {
      (written.duration >= plan.duration - frame && written.duration <= plan.duration + frame + accessUnit) shouldBe
        true
    }

    // Measured off the end of the decode rather than from an instant the container named, since the
    // two clocks are what this is comparing in the first place.
    val tail = written.duration - plan.duration - frame
    if (tail <= Duration.ZERO) return
    val from = decoded.duration - tail
    val bed = decoded.amplitudeOver(from, tail, BED_HZ)
    val primary = decoded.amplitudeOver(from, tail, PRIMARY_HZ)
    withClue(
      "the last $tail of the decode carries $bed at $BED_HZ and $primary at $PRIMARY_HZ, so the file " +
        "runs long with sound still in it rather than on an encoder's flush",
    ) {
      (bed <= tones.bed * SILENT_TAIL && primary <= tones.primary * SILENT_TAIL) shouldBe true
    }
  }

