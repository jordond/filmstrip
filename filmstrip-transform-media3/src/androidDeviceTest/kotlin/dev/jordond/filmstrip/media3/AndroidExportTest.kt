  private companion object {
    // The fixtures' own rate, so every frame of a clip can land on a slot of its own.
    const val GRID_RATE = 30

    // A rate that a pass of LoopingCases.VIDEO_TRIM is not a whole number of slots at.
    const val OFF_GRID_RATE = 25

    // A seam just past a slot and one just short of the next, which round opposite ways.
    val SEAMS = listOf(1_010.milliseconds, 1_020.milliseconds)

    // Half way between the fixture's first two frames.
    val INSIDE_A_FRAME = 16_667.microseconds

    // One frame of a GRID_RATE fixture.
    val FIXTURE_FRAME = 1.seconds / GRID_RATE

    // A copy of CLIP that ends on its second sync sample, which lasts less than a frame. Past half a
    // slot, so the slot it sits in is the last one a pass covers, and short of the slot's end.
    const val SHORT_CLIP = "android_export_short.mp4"
    val SHORT_LAST_FRAME_LASTS = 23.milliseconds + 334.microseconds

    const val CLIP_LONG = "android_export_long.mp4"
    const val CLIP_ROTATED = "android_export_rotated.mp4"
    const val CLIP_BED = "tone_bed_880.mp4"

    // A window inside CLIP_LONG's twelve seconds, opening between two of its sync samples rather
    // than on one, since a cut that already sits on a key frame snaps nowhere and would pass
    // whether the snap works or not. CLIP_LONG is encoded with a key frame every second, so this
    // cut sits half a second past the sync sample it snaps back to.
    val TRIM_START = 4_500.milliseconds
    val TRIM_END = 7_250.milliseconds

    // Comfortably past the half second gap TRIM_START leaves to reach a sync sample.
    val SNAP_WITHIN = 1.seconds

    // Comfortably short of that same gap, so the cut is never mistaken for one the snap reaches.
    val TOO_NARROW_TO_SNAP = 100.milliseconds

    // The one frequency the bed carries and no other fixture does, against the one every other
    // fixture carries. Separating them is what lets a level in the mix be read back to a source.
    const val PRIMARY_HZ = 440
    const val BED_HZ = 880

    const val BED_VOLUME = 0.5f

    // The bed's clip, and the gap in front of it. Different lengths on purpose. A pass has to open
    // every BED_PASS once the bed has started, the way it does on the other three backends, and a
    // reading that counted the gap into the period would open one every BED_START + BED_PASS and
    // leave silence between. Equal lengths hide that, since a pass lands under MIDDLE_AT either way.
    val BED_START = 600.milliseconds
    val BED_PASS = 400.milliseconds

    // Two windows into the primary's two seconds: one in the gap before the bed opens, one in a
    // stretch the bed only covers when its passes run back to back. A period that counted the gap
    // in would be silent across the second of them. Both sit 100ms clear of a boundary, which is
    // more than the priming an AAC decoder can shift the whole run by.
    val EARLY_AT = 100.milliseconds
    val MIDDLE_AT = 1_200.milliseconds
    val WINDOW = 200.milliseconds

    // The fade test's own bed, whose pass is longer than the loop test's so the ramp has room to be
    // read across its range, with a stretch past the ramp's top to read the plateau on.
    val FADE_PASS = 1_200.milliseconds
    val FADE_LENGTH = 800.milliseconds

    // Where the ramp is read, in the bed clip's own time. Three points across it and one past its
    // top, which is what says the ramp stopped at the peak instead of climbing through it. Every
    // window sits 150ms clear of the stretch it measures.
    val RAMP_AT = listOf(200.milliseconds, 400.milliseconds, 600.milliseconds, 1_000.milliseconds)

    // Short enough to sit inside the stretch it measures, and a whole number of cycles of both
    // tones, so neither leaks into the other's reading.
    val RAMP_WINDOW = 100.milliseconds

    // The floor a window's primary tone has to clear against its own source level for the division
    // that recovers a gain to mean anything. Not an accuracy bound, which is
    // ToneAnalysis.MEASURED_GAIN_TOLERANCE and shared with the other three backends.
    const val AUDIBLE = 0.5f

    // How long the muxer gets to create the file, and how often it is looked for.
    val MUXER_OPENS = 10.seconds
    val POLL = 10.milliseconds

    // A trim lands on frame boundaries, and a container's reported duration rounds.
    val DURATION_TOLERANCE = 150.milliseconds

    // Encoders align to their own multiple, which is 2 on most and 16 on some.
    const val SIZE_TOLERANCE = 16

    // Long enough to hold every tone in a window without reaching a pass boundary, and a whole
    // number of cycles of both frequencies so neither leaks into the other's reading.
    val LOOP_WINDOW = 200.milliseconds

    // How far into a pass the two matching frames are read. The same distance into two passes is
    // the same instant of the source, so the pictures have to match. FRAME_ELSEWHERE is a second
    // instant of the source, a whole second away inside the first pass, that they both have to
    // differ from.
    val FRAME_INTO = 400.milliseconds
    val FRAME_ELSEWHERE = 1_400.milliseconds

    // Where the frame is sampled, as fractions of a 320x240 output. The color bars across the top
    // and the block in the middle hold still between frames of the source; the digits the pattern
    // counts with sit around the middle and the one band that sweeps is near the bottom, which is
    // MOVING_BAND and the only row that can tell two instants of the source apart.
    val FRAME_ACROSS = listOf(0.2f, 0.5f, 0.8f)
    const val MOVING_BAND = 0.8f
    val FRAME_DOWN = listOf(0.2f, 0.5f, MOVING_BAND)

    // The three channels summed, out of 765. The fill is black, so a frame carrying any of the
    // pattern clears this comfortably and a frame of fill cannot.
    const val LIT = 200

    // Two encodes of one source frame differ by rounding and by what the encoder spent its bits on,
    // and by nothing like the gap between a picture and a flat color.
    const val FRAME_TOLERANCE = 150

    const val MILLIS_PER_SECOND = 1_000

    // The samples one AAC access unit carries, divided by the rate the decode ran at to give media3
    // its own limit on how far past the plan a file may run, which is the only allowance made.
    // The clipping configuration is set in milliseconds (Media3Composition's setStartPositionMs), so
    // a clip opening part way through an access unit opens on the unit before it and that whole unit
    // reaches the muxer, and the encoder's flush rounds up what is left. Measured on the emulator:
    // the case one bed trimmed from 200ms wrote 7.348s against a 7.300s plan, and the same pass
    // length trimmed from zero wrote 7.327s, one unit shorter.
    const val AAC_UNIT_SAMPLES = 1_024

    // What the tail may carry of either source's own level and still count as silence. The measured
    // tails read under half a percent, and a pass that ran on past the plan would read most of one.
    const val SILENT_TAIL = 0.01f
  }
