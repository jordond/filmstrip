/**
 * Four frames of H.264 at 128 by 72, written by ffmpeg 9.0.2's libx264 from the same BT.601 limited range codes, four
 * mid range bars side by side.
 *
 * Each carries its tags in the bitstream and in the `colr` box, the way a real SD file does, and comes to two
 * kilobytes.
 *
 * The bytes come from this, with `setparams` naming the clip's own tags and left out for the untagged one:
 * ```
 * ffmpeg -f rawvideo -pix_fmt yuv420p -s 128x72 -r 30 -i bars.yuv \
 * -vf setparams=color_primaries=smpte170m:color_trc=smpte170m:colorspace=smpte170m:range=tv \
 * -c:v libx264 -profile:v baseline -preset veryslow -qp 6 -g 4 -bf 0 -map_metadata -1 -bitexact -flags:v +bitexact \
 * -x264-params no-info=1 -movflags +faststart clip.mp4
 * ```
 */
internal object SdClips {
  /**
   * Tagged with SMPTE 170M primaries, transfer and matrix.
   */
  val smpte170m: ByteArray get() = decoded(SMPTE_170M)

  /**
   * Tagged with EBU primaries and a BT.470 BG matrix, on SMPTE 170M's transfer.
   */
  val ebu: ByteArray get() = decoded(EBU)

  /**
   * Tagged with nothing at all.
   */
  val untagged: ByteArray get() = decoded(UNTAGGED)

  @OptIn(ExperimentalEncodingApi::class)
  private fun decoded(clip: String): ByteArray = Base64.decode(clip)
}

