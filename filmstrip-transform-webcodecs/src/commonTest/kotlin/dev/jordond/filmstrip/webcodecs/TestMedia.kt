/**
 * A colour, as the eight-bit channels a test asserts on.
 */
internal class Rgb(
  val red: Int,
  val green: Int,
  val blue: Int,
) {
  /**
   * True when every channel is within [tolerance] of [other]. Colour survives a 4:2:0 round trip
   * approximately, never exactly.
   */
  fun isNear(
    other: Rgb,
    tolerance: Int = DEFAULT_TOLERANCE,
  ): Boolean =
    abs(red - other.red) <= tolerance &&
      abs(green - other.green) <= tolerance &&
      abs(blue - other.blue) <= tolerance

  override fun toString(): String = "rgb($red, $green, $blue)"

  companion object {
    const val DEFAULT_TOLERANCE = 24

    val Black = Rgb(0, 0, 0)
    val Red = Rgb(220, 30, 30)
    val Blue = Rgb(30, 30, 220)
    val Green = Rgb(30, 200, 30)
    val Grey = Rgb(200, 200, 200)
  }
}

/**
 * One decoded frame of an export, with its pixels in memory so a test can look at a position rather
 * than only at a dimension.
 */
internal class OutputFrame(
  val timestampUs: Double,
  val durationUs: Double,
  val width: Int,
  val height: Int,
  private val rgba: Uint8Array,
) {
  /**
   * The colour at a point given as fractions of the frame, measured from the top left the way
   * filmstrip measures everything else.
   */
  fun at(
    x: Double,
    y: Double,
  ): Rgb {
    val column = (x * width).toInt().coerceIn(0, width - 1)
    val row = (y * height).toInt().coerceIn(0, height - 1)
    val offset = (row * width + column) * RGBA_CHANNELS
    return Rgb(rgba.at(offset), rgba.at(offset + 1), rgba.at(offset + 2))
  }
}

/**
 * Muxes [frames] frames of [width] by [height] into an MP4 and hands the file back.
 *
 * Built here rather than committed, so the test media is a few kilobytes of generated bytes instead
 * of a binary in the tree. [row] paints one scanline at a time, which is all the fixtures need and
 * is what lets a test tell the top of a frame from the bottom.
 */
internal suspend fun makeClip(
  width: Int = 64,
  height: Int = 64,
  frames: Int = 12,
  frameRate: Int = 30,
  row: (frameIndex: Int, y: Int) -> Rgb,
): ByteArray {
  val target = BufferTarget()
  val output =
    Output(
      JsOptions()
        .put("format", Mp4OutputFormat())
        .put("target", target)
        .build(),
    )
  val source =
    VideoSampleSource(
      JsOptions()
        .put("codec", "avc")
        .put("fullCodecString", "avc1.42001F")
        .put("quality", Quality(JsOptions().put("bitrate", FIXTURE_BITRATE).build()))
        .put("keyFrameInterval", 1.0)
        .build(),
    )
  output.addVideoTrack(source, JsOptions().put("frameRate", frameRate).build())
  output.start().await()

  val pixels = ByteArray(width * height * RGBA_CHANNELS)
  for (index in 0 until frames) {
    for (y in 0 until height) {
      val colour = row(index, y)
      for (x in 0 until width) {
        val offset = (y * width + x) * RGBA_CHANNELS
        pixels[offset] = colour.red.toByte()
        pixels[offset + 1] = colour.green.toByte()
        pixels[offset + 2] = colour.blue.toByte()
        pixels[offset + 3] = OPAQUE
      }
    }
    val sample =
      VideoSample(
        pixels.toUint8Array(),
        JsOptions()
          .put("format", "RGBA")
          .put("codedWidth", width)
          .put("codedHeight", height)
          .put("timestamp", index.toDouble() / frameRate)
          .put("duration", 1.0 / frameRate)
          .build(),
      )
    try {
      source.add(sample).await()
    } finally {
      sample.close()
    }
  }

  output.finalize().await()
  return (target.buffer ?: error("the fixture muxer produced no buffer")).toByteArray()
}

/**
 * A solid clip, for the cases where only the timing matters.
 */
internal suspend fun makeClip(
  width: Int = 64,
  height: Int = 64,
  frames: Int = 12,
  frameRate: Int = 30,
  colour: Rgb = Rgb.Grey,
): ByteArray = makeClip(width, height, frames, frameRate) { _, _ -> colour }

