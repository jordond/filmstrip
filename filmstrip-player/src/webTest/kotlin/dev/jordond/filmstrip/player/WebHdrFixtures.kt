/**
 * The HDR clip a web suite plays in [transfer], carried in the source as bytes for the reason [webFixtureComposition]
 * gives.
 *
 * Each is half a second of one flat colour at 64 by 64, ten-bit VP9 in BT.2020 tagged with its transfer, encoded
 * lossless so the codes it decodes to are the codes it was written with. Both were made with
 * `ffmpeg -f lavfi -i "color=c=0x8a6a50:s=64x64:r=30:d=0.5,format=yuv420p10le,setparams=color_primaries=bt2020:
 * color_trc=<smpte2084|arib-std-b67>:colorspace=bt2020nc:range=tv" -c:v libvpx-vp9 -profile:v 2 -lossless 1 -g 1
