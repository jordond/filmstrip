/**
 * A page cannot read a file off disk and this module has no muxer of its own, so the clip every web
 * contract suite plays is carried in the source as bytes.
 *
 * Colour bars with a white block sliding across them: detail enough for a similarity metric to mean
 * something, and different enough frame to frame that a preview drawing the wrong instant does not
 * match the export of the right one. It carries a tone as well, because the engine's clock branches
 * on whether a composition has audio and a silent fixture would only ever reach one branch.
 */
private val FIXTURE_CLIP: ByteArray by lazy { Base64.decode(FIXTURE_BASE64.filterNot(Char::isWhitespace)) }

/**
 * One trimmed clip of the fixture, with [effects] over the whole composition.
 *
 * @param audio Whether the fixture's tone survives into the composition, which is what decides
 *   which clock the engine runs on.
 */
internal fun webFixtureComposition(
  effects: List<EffectSpec> = emptyList(),
  audio: AudioSpec = AudioSpec.Remove,
): EditComposition =
  EditComposition(
    tracks = listOf(Track(listOf(Clip(MediaSource.Bytes(FIXTURE_CLIP), TimeRange.of(Duration.ZERO, CLIP_LENGTH))))),
    effects = effects,
    audio = audio,
  )

/**
 * The frame the export writes at [position], read back out of the file the encoder wrote.
 *
 * This is the export path and not a second preview: the edit is planned and exported through the
 * public facade, the muxed file is handed back as a blob, and the frame is decoded out of it by a
 * reader that never saw the encoder. The decoded frame goes through one identity compositor pass on
 * its way to packed RGBA, which is the same conversion the preview's read-back takes, so what is
 * left between the two sides is the lowering and the encode.
 */
@OptIn(InternalFilmstripApi::class)
internal suspend fun webExportFrame(
  composition: EditComposition,
  position: Duration,
): TestFrame {
  val statuses = CONTRACT_FILMSTRIP.export(exportPlanOf(composition), MediaSink.Uri("")).toList()
  statuses.filterIsInstance<ExportStatus.Failure>().firstOrNull()?.let {
    fail("the export failed: ${it.error.message}")
  }
  val success =
    statuses.filterIsInstance<ExportStatus.Success>().singleOrNull()
      ?: fail("the export produced ${statuses.map { it::class.simpleName }}")
  val url = (success.output as? MediaSink.Uri)?.uri ?: fail("the export handed back ${success.output}")

  val written = EditComposition(tracks = listOf(Track(listOf(Clip(MediaSource.Uri(url))))), audio = AudioSpec.Remove)
  val engine = browserExportEngine(CONTRACT_COMPONENTS, chainedProber(CONTRACT_COMPONENTS))
  val resolved =
    when (val result = engine.resolve(written, ExportSpec())) {
      is ResolveResult.Refused -> fail("the exported file could not be read back: ${result.error.message}")
      is ResolveResult.Resolved -> result.composition
    }

  val preview = resolved.toBrowserPreview(written)
  try {
    val frame = preview.frameAt(position) ?: fail("the export has no frame at $position")
    return TestFrame(frame.pixels, frame.size)
  } finally {
    preview.release()
  }
}

private suspend fun exportPlanOf(composition: EditComposition): ExportPlan =
  when (val verdict = CONTRACT_FILMSTRIP.plan(composition, ExportSpec())) {
    is Verdict.Capable -> verdict.plan
    is Verdict.Degraded -> verdict.plan
    is Verdict.Incapable -> fail("the export refused the fixture: ${verdict.reasons.map { it.message }}")
  }

/**
 * The components a host that registered the WebCodecs backend would hand a preview.
 *
 * Both sides of the pixel contract lower through this one registry, so a difference between them is
 * a difference in how the graph is built rather than in what was registered.
 */
internal val CONTRACT_FILMSTRIP: Filmstrip = Filmstrip { webCodecsBackend() }

internal val CONTRACT_COMPONENTS: ComponentRegistry = CONTRACT_FILMSTRIP.components

/**
 * Long enough to play through and seek inside, and a whole number of frames at the fixture's rate.
 */
internal val CLIP_LENGTH: Duration = 1500.milliseconds

/**
 * The frame the fixture decodes at, which is the frame an export of it writes.
 */
internal val FIXTURE_FRAME: Size = Size(128, 96)

/**
 * Composition times the pixel suite compares at, each landing exactly on the fixture's 30fps grid.
 */
internal val PROBE_POSITIONS: List<Duration> = listOf(300.milliseconds, 900.milliseconds)

