      top = pixelAt(output.absolutePath, size.width / 2, 2),
      bottom = pixelAt(output.absolutePath, size.width / 2, size.height - 2),
      centre = pixelAt(output.absolutePath, size.width / 2, size.height / 2),
    ).also { output.delete() }
  }

