  /**
   * The colour tags and the pixel format, the four fields that decide whether a file is HDR.
   *
   * Reported together because a 10-bit frame with Rec.709 tags and an 8-bit frame with BT.2020 tags
   * are both wrong, and either one alone reads as a pass.
   */
  private fun colorTags(path: String): String {
    val process =
      ProcessBuilder(
        "ffprobe",
        "-v",
        "error",
        "-select_streams",
        "v:0",
        "-show_entries",
        "stream=pix_fmt,color_primaries,color_transfer,color_space",
        "-of",
        "default=noprint_wrappers=1",
        path,
      ).start()
    val output = process.inputReader().readText()
    process.waitFor()

    // ffprobe prints these in its own order rather than the order they were asked for, so they are
    // read by key and put back in one this test can pin.
    val fields =
      output
        .lineSequence()
        .mapNotNull { line -> line.split("=", limit = 2).takeIf { it.size == 2 } }
        .associate { it[0].trim() to it[1].trim() }

    return listOf("pix_fmt", "color_primaries", "color_transfer", "color_space")
      .joinToString(" ") { fields[it] ?: "unknown" }
  }

  private fun ffprobe(path: String): String {
    val process =
      ProcessBuilder(
        "ffprobe",
        "-v",
        "error",
        "-show_entries",
        "stream=codec_type,codec_name,width,height,avg_frame_rate",
        "-of",
        "default=noprint_wrappers=1",
        path,
      ).start()
    val output = process.inputReader().readText()
    process.waitFor()

    val fields =
      output
        .lineSequence()
        .mapNotNull { line -> line.split("=", limit = 2).takeIf { it.size == 2 } }
        .groupBy({ it[0].trim() }, { it[1].trim() })

    return "${fields["width"]!!.first()}x${fields["height"]!!.first()} " +
      "${fields["avg_frame_rate"]!!.first()} " +
      fields["codec_name"]!!.joinToString(" ")
  }

  private companion object {
    val TIMEOUT = kotlin.time.Duration.parse("2m")

    // Long enough for a loaded runner to open the encoder, short of the runTest timeout.
    val ENCODE_DEADLINE = kotlin.time.Duration.parse("30s")
    const val RED = 0xFFFF0000.toInt()
    const val HALF = 0.5f
    const val BRIGHTER = 1.5f

    // Comfortably above half of RED's own red channel and comfortably below assertReddish's own
    // floor, so a bar that read halved fails here rather than by accident of a bound written for a
    // different purpose.
    const val HALVED_RED_CEILING = 180

    // A window inside the long fixture's twelve seconds, opening between two of its sync samples
    // rather than on one, since a cut that already sits on a sync sample snaps nowhere and would
    // pass whether the snap works or not.
    val TRIM_START = 4_500.milliseconds
    val TRIM_END = 7_250.milliseconds

    // Wider than the fixture's own one-second sync interval, so the sample before the cut is
    // reachable with room to spare rather than only just.
    val SNAP_WITHIN = 2.seconds

    // How far a written run may sit from the window the plan resolved. A bounded copy ends on a
    // whole packet rather than on the length it was given, and this build overshoots by around
    // 80ms of it. Still well short of the group of pictures a cut that snapped when it should not
    // have, or did not when it should have, would move by.
    val COPY_SLOP = 200.milliseconds

    // How far a remux may land from the source it copied. The mp4 muxer sizes its own padding, and
    // ffmpeg 6 writes a byte more of it than later builds do. A re-encode of this fixture misses by
    // tens of kilobytes, so the band separates the two readings without pinning a muxer's spelling.
    const val CONTAINER_DRIFT_BYTES = 64L

    // A 2x2 crop of one plane at two bytes a sample.
    const val PLANE_BYTES = 8
    const val TEN_BIT_MAX = 1023f

    // What a real HEVC encode and a 4:2:0 chroma round trip leave on a ten-bit code value. The two
    // readings this separates are hundreds of code values apart, so the band is generous without
    // being blind.
    const val CODE_DRIFT = 40

    // Where a ten-bit channel carries more than the fixture's own noise floor and the slop a
    // chroma round trip leaves.
    const val SIGNAL_FLOOR = 128

    // How close to PQ's peak a reading has to get to count as having hit the format's ceiling
    // rather than the effect's answer.
    const val HEADROOM = 0.9f

    // How far off half the encoder and a 4:2:0 round trip are allowed to leave the halved signal.
    // Halving linear light instead would read about three quarters of the signal, well outside
    // this, which is what makes the band worth asserting rather than a plain "darker".
    const val SIGNAL_DRIFT = 0.05f

    // What a full eight-bit channel reads as, which is what the shared matrix's zero-to-one answer
    // is scaled by.
    const val FULL_SCALE = 255f

    // SIGNAL_DRIFT's width in code values. A matrix answers per channel rather than as one signal,
    // so each channel is given the same band the halved signal gets.
    const val CHANNEL_DRIFT = (SIGNAL_DRIFT * FULL_SCALE).toInt()

    // Half of the two-second fixture, so the curve still holds flat for a second afterwards.
    val FADE = 1_000.milliseconds

    // Where the ramp is read back. Quarters of the fade, so what is asserted is the middle of the
    // range as much as its ends, and every one of them lands inside both curves under test.
    val RAMP_READINGS = listOf(250.milliseconds, 500.milliseconds, 750.milliseconds, FADE)

    // Where the reading every other one is scaled by comes from, clear of the fixture's own end.
    val REFERENCE_AT = 1_500.milliseconds

    // Enough pinned points to outrun what one volume node's expression carries, laid close enough
    // together to stay inside the two-second fixture.
    const val CHAINED_POINTS = 120
    val RAMP_STEP = 16.milliseconds

    // The rate the readback decodes to, which is also the rate every fixture carries.
    const val AUDIO_SAMPLE_RATE = 48_000

    // Twenty milliseconds, more than eight cycles of the fixture's own 440 Hz tone. Long enough for
    // the root mean square to settle and short enough that the curve barely moves across it.
    const val ENVELOPE_WINDOW_SAMPLES = AUDIO_SAMPLE_RATE / 50

    // How far a reading of the ramp may sit from the curve. What this separates is a fade of the
    // wrong length or shape, which misses by a quarter of full scale at the points asserted.
    const val ENVELOPE_DRIFT = 0.03f

    // The bed's tone and the one every other fixture carries. Two frequencies rather than one is
    // what lets a reading of the mix say which source it belongs to.
    const val BED_HZ = 880
    const val PRIMARY_HZ = 440

    // Half, so a bed that reached the file untouched reads twice what the plan folded.
    const val BED_GAIN = 0.5f

    // Late enough to leave a stretch of the timeline with no bed on it, and early enough that the
    // three second bed is laid down again before the middle of the twelve second primary.
    val BED_START = 1_000.milliseconds

    // Long enough that a measurement window sits well inside either ramp with room to spare, and
    // different from each other so a fade in swapped for a fade out is not the same curve twice.
    // Together they leave the three second bed a stretch at full level between them.
    val BED_FADE_IN = 1_200.milliseconds
    val BED_FADE_OUT = 900.milliseconds

    // Before the bed starts, where the mix carries the primary alone.
    val QUIET_READING = 500.milliseconds

    // The middle of the timeline, which by then is a loop pass past the bed's own end.
    val MIXED_READING = 5_500.milliseconds

    // Where a fixture's own tone is read, clear of both its ends.
    val FIXTURE_READING = 1_000.milliseconds

    // A hundred milliseconds, eighty-eight cycles of the bed's tone. Long enough for the two
    // frequencies to separate cleanly and short enough to sit inside one loop pass.
    const val TONE_WINDOW_SAMPLES = AUDIO_SAMPLE_RATE / 10
  }
