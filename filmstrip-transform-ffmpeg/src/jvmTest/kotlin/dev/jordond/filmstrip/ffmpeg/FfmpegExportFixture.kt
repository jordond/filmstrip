/**
 * What every end-to-end export suite shares: the fixture clips, a [Filmstrip] on the ffmpeg backend, and the helpers
 * that plan an edit and export it. A suite holds one as a field, so each test instance gets its own.
 *
 * A test skips rather than fails when there is no ffmpeg, because the fixtures are generated by the same binary the
 * export drives, so the two are available together or not at all.
 */
internal class FfmpegExportFixture {
  internal val fixtures = File(System.getProperty("filmstrip.fixtures").orEmpty())
  internal val landscape = File(fixtures, "export_landscape.mp4")
  internal val portrait = File(fixtures, "export_portrait.mp4")
  internal val long = File(fixtures, "export_long.mp4")
  internal val bed = File(fixtures, "tone_bed_880.mp4")
  internal val hdr = File(fixtures, "export_hdr.mp4")
  internal val hdrHlg = File(fixtures, "export_hdr_hlg.mp4")

  internal val filmstrip = Filmstrip { ffmpegBackend() }

  /**
   * The plan for [composition], with a frame the encoder had to align allowed through.
   *
   * Scaling the long fixture to the spec's target height lands between two widths the encoder
   * accepts, which the planner reports as an adjustment and which none of these tests measure.
   */
  internal suspend fun plannedRun(
    composition: EditComposition,
    spec: ExportSpec,
  ): ExportPlan =
    when (val verdict = filmstrip.plan(composition, spec)) {
      is Verdict.Capable -> {
        verdict.plan
      }
      is Verdict.Degraded -> {
        verdict.plan.also {
          val frameOnly =
            verdict.adjustments.isNotEmpty() &&
              verdict.adjustments.all { adjustment -> adjustment.kind == AdjustmentKind.ResolutionClamped }
          assertTrue(
            frameOnly,
            "the plan degraded for more than the frame: ${verdict.adjustments.map { it.message }}",
          )
        }
      }
      is Verdict.Incapable -> {
        error("the edit cannot run: ${verdict.reasons}")
      }
    }

  /**
   * Runs [plan] into [output] and hands back what the file it wrote says about itself.
   */
  internal suspend fun exported(
    plan: ExportPlan,
    output: File,
  ): MediaInfo {
    val finished = filmstrip.export(plan, MediaSink.of(output.absolutePath)).toList().last()
    if (finished is ExportStatus.Failure) error(finished.error.message)
    return assertIs<ExportStatus.Success>(finished).info
  }

  /**
   * The tracks the planner resolved for [composition], so a reading is measured against the gain the
   * export ran rather than against a number written here.
   */
  internal suspend fun plannedTracks(
    composition: EditComposition,
    spec: ExportSpec,
    sources: List<MediaSource>,
  ): List<ResolvedTrack> = assertNotNull(plannedLowering(composition, spec, sources).export.composition).tracks

  /**
   * What the planner lowered [composition] to, so a count is read off the composition it negotiated and the graph it
   * wrote rather than off a number worked out here.
   */
  internal suspend fun plannedLowering(
    composition: EditComposition,
    spec: ExportSpec,
    sources: List<MediaSource>,
  ): Lowering {
    val located = ToolchainLocator(FfmpegConfig(), ProcessRunner()).toolchain()
    val toolchain = assertIs<ToolchainResult.Available>(located).toolchain
    val device = assertIs<CapabilitiesResult.Success>(filmstrip.capabilities()).capabilities
    val infos = sources.associateWith { assertIs<ProbeResult.Success>(filmstrip.probe(it)).info }
    val runtime = FfmpegRuntime.of(FfmpegConfig())
    val openings =
      copyOpenings(composition) { source, cut ->
        runtime.syncSampleAtOrBefore(toolchain, assertNotNull(readablePath(source)), cut)
      }
    return FfmpegPlanner(toolchain, listOf(BuiltInEffectResolver()))
      .lower(composition, spec, device, infos, openings)
  }

  internal fun available(): Boolean = landscape.isFile && portrait.isFile

  /**
   * The decoded pixels of the one frame presented at [at], as RGB.
   *
   * Two decodes of the same picture agree byte for byte, so this is what says an output opened on
   * one source frame rather than another. Verified independently of the code under test.
   */
  internal fun frameAt(
    path: String,
    at: Duration,
  ): ByteArray {
    val process =
      ProcessBuilder(
        "ffmpeg",
        "-hide_banner",
        "-loglevel",
        "error",
        "-ss",
        formatSeconds(at.toDouble(DurationUnit.SECONDS)),
        "-i",
        path,
        "-frames:v",
        "1",
        "-f",
        "rawvideo",
        "-pix_fmt",
        "rgb24",
        "-",
      ).start()
    val frame = process.inputStream.readBytes()
    process.waitFor()
    assertTrue(frame.isNotEmpty(), "ffmpeg decoded no frame at $at of $path")
    return frame
  }

  /**
   * One export of the landscape fixture, with [overlay] drawn on its only clip or with nothing at
   * all.
   *
   * The plan comes back with it, because the output frame and the composition's length are what the
   * shared overlay sampler is asked against and reading them off the plan is what keeps a test from
   * restating a fixture's dimensions.
   */
  internal suspend fun exportedWatermark(
    name: String,
    overlay: ImageOverlay?,
    clips: Int = 1,
    onClip: Boolean = false,
    spec: ExportSpec = ExportSpec(),
  ): ExportedOverlay {
    val output = File.createTempFile(name, ".mp4").also { it.delete() }
    val composition =
      compositionOf {
        repeat(clips) { index ->
          clip(MediaSource.of(landscape.absolutePath)) {
            if (onClip && index == clips - 1) overlay?.let { mark -> effects { add(mark) } }
          }
        }
        if (!onClip) overlay?.let { mark -> effects { add(mark) } }
      }

    val plan =
      when (val verdict = filmstrip.plan(composition, spec)) {
        is Verdict.Capable -> verdict.plan
        is Verdict.Degraded -> verdict.plan
        is Verdict.Incapable -> error(verdict.reasons.joinToString { it.message })
      }
    val finished = filmstrip.export(plan, MediaSink.of(output.absolutePath)).toList().last()
    if (finished is ExportStatus.Failure) error(finished.error.message)
    assertIs<ExportStatus.Success>(finished)

    return ExportedOverlay(output, plan)
  }

  /**
   * One export of the landscape fixture contained in a portrait frame over a [fill] fill, with [overlay] on the
   * composition or with nothing at all.
   *
   * [underFill] adds a brightness ahead of the overlay, which holds the fill back until it has run. [lead] starts the
   * primary that far in, leaving the fill to every slot ahead of it.
   */
  internal suspend fun exportedOverFill(
    name: String,
    overlay: ImageOverlay?,
    underFill: Boolean = false,
    lead: Duration = Duration.ZERO,
    fill: Int = BAR_FILL,
  ): ExportedOverlay {
    val output = File.createTempFile(name, ".mp4").also { it.delete() }
    val composition =
      compositionOf {
        track {
          clip(MediaSource.of(landscape.absolutePath))
          if (lead > Duration.ZERO) startAt(lead)
        }
        effects {
          crop(AspectRatio.Portrait, fit = Fit.Contain)
          if (underFill) brightness(HALF)
          overlay?.let { add(it) }
        }
        fill(Fill.Solid(fill))
      }

    val plan =
      when (val verdict = filmstrip.plan(composition, ExportSpec())) {
        is Verdict.Capable -> verdict.plan
        is Verdict.Degraded -> verdict.plan
        is Verdict.Incapable -> error(verdict.reasons.joinToString { it.message })
      }
    val finished = filmstrip.export(plan, MediaSink.of(output.absolutePath)).toList().last()
    if (finished is ExportStatus.Failure) error(finished.error.message)
    assertIs<ExportStatus.Success>(finished)

    return ExportedOverlay(output, plan)
  }

  // A flat square in a colour no bar of the testsrc fixture carries, so the blend under it is well
  // conditioned in every channel wherever the overlay lands.
  internal fun watermark(
    corner: Corner = Corner.TopStart,
    opacity: Float = 1f,
    animation: OverlayAnimation? = null,
    image: Size = OVERLAY_SIZE,
  ): ImageOverlay =
    ImageOverlay(
      image = ImageSource.ofBytes(watermarkPng(image)),
      corner = corner,
      opacity = opacity,
      animation = animation,
    )

  internal val watermarkPngs = mutableMapOf<Size, ByteArray>()

  internal fun watermarkPng(size: Size): ByteArray = watermarkPngs.getOrPut(size) { pngOf(OVERLAY_COLOUR, size) }
}

/**
 * The values the end-to-end export suites share, from the fixture colours and audio tones to the frames and rates a
 * reading is taken at. A suite imports the ones it reads.
 */
internal object ExportConstants {
  val TIMEOUT = kotlin.time.Duration.parse("2m")

  // The indexed clips' colours. Blue names the clip, and red and green step by INDEX_STEP from INDEX_FLOOR, far
  // enough apart that a re-encode moving a flat colour by a few values still reads the same index.
  val CLIP_BLUES = listOf(60, 140, 220)
  val FIRST_BLUE = CLIP_BLUES[0]
  val SECOND_BLUE = CLIP_BLUES[1]
  val THIRD_BLUE = CLIP_BLUES[2]
  const val INDEX_FLOOR = 20
  const val INDEX_STEP = 20
  val INDEXED_SIZE = Size(320, 180)

  // A quarter of each side, centred, which crop does when it is given no offset.
  const val MIDDLE_CROP = "crop=w=iw/4:h=ih/4"

  const val MICROS_PER_SECOND = 1_000_000.0

  // Long enough for a loaded runner to open the encoder, short of the runTest timeout.
  val ENCODE_DEADLINE = kotlin.time.Duration.parse("30s")
  const val RED = 0xFFFF0000.toInt()
  const val HALF = 0.5f
  const val BRIGHTER = 1.5f

  // What a real HEVC encode and a 4:2:0 chroma round trip leave on a ten-bit code value. The two
  // readings this separates are hundreds of code values apart, so the band is generous without
  // being blind.
  const val CODE_DRIFT = 40

  // The rate the readback decodes to, which is also the rate every fixture carries.
  const val AUDIO_SAMPLE_RATE = 48_000

  // Twenty milliseconds, more than eight cycles of the fixture's own 440 Hz tone. Long enough for
  // the root mean square to settle and short enough that the curve barely moves across it.
  const val ENVELOPE_WINDOW_SAMPLES = AUDIO_SAMPLE_RATE / 50

  // The bed's tone and the one every other fixture carries. Two frequencies rather than one is
  // what lets a reading of the mix say which source it belongs to.
  const val BED_HZ = 880
  const val PRIMARY_HZ = 440

  // Half, so a bed that reached the file untouched reads twice what the plan folded.
  const val BED_GAIN = 0.5f

  // Late enough to leave a stretch of the timeline with no bed on it, and early enough that the
  // three second bed is laid down again before the middle of the twelve second primary.
  val BED_START = 1_000.milliseconds

  // Before the bed starts, where the mix carries the primary alone.
  val QUIET_READING = 500.milliseconds

  // Where a fixture's own tone is read, clear of both its ends.
  val FIXTURE_READING = 1_000.milliseconds

  // A hundred milliseconds, eighty-eight cycles of the bed's tone. Long enough for the two
  // frequencies to separate cleanly and short enough to sit inside one loop pass.
  const val TONE_WINDOW_SAMPLES = AUDIO_SAMPLE_RATE / 10

  const val RGB_CHANNELS = 3

  // Just over one frame of the fixtures' thirty per second. A read lands on the first frame at or
  // after where it opens, so this reaches the last frame of a run rather than running off the end.
  val FRAME = 40.milliseconds

  // Half the smallest gap between the watermark's colour and any bar of the fixture it is drawn
  // over, so a covered probe and an uncovered one cannot be confused for each other.
  const val DRAWN_DIFFERENCE = 50.0

  // The whole of a fixture clip, so a quarter and three quarters of the ramp are half a second
  // and a second and a half into it.
  val RAMP = 2.seconds

  // Below this the two references are too close together for the blend to be solved at all, which
  // is a probe point chosen badly rather than a lowering that went wrong.
  const val BLEND_RANGE_FLOOR = 1_000.0
  val INSIDE_WINDOW = 3.seconds
  val OUTSIDE_WINDOW = listOf(2_200.milliseconds, 3_800.milliseconds)

  // How far ahead of a frame's own time a read opens, so that it lands on that frame rather than
  // the one after it. Shorter than a frame period at either rate these tests export at.
  val FRAME_LEAD = 10.milliseconds

  // The rates the frame grid is measured at: the fixtures' own thirty, and twenty five, whose 40 ms slot puts a
  // half slot on a whole millisecond.
  const val SEAM_RATE = 30
  const val GRID_RATE = 25
}
